export const translateTamilText = (value) => {
  const exact = translations.ta[value]
  if (exact) return exact
  const required = value.match(/^(.+?)(\s*\*)$/)
  if (required && translations.ta[required[1]]) return `${translations.ta[required[1]]}${required[2]}`
  const colon = value.match(/^(.+?)(:)$/)
  if (colon && translations.ta[colon[1]]) return `${translations.ta[colon[1]]}${colon[2]}`
  const insensitive = Object.entries(translations.ta).find(([key]) => key.toLocaleLowerCase('en') === value.toLocaleLowerCase('en'))
  if (insensitive) return insensitive[1]
  const patterns = [
    [/^Good (morning|afternoon|evening), (.+)$/i, (_, period, name) => `${period.toLowerCase() === 'morning' ? 'காலை வணக்கம்' : period.toLowerCase() === 'afternoon' ? 'மதிய வணக்கம்' : 'மாலை வணக்கம்'}, ${name}`],
    [/^(\d+) unread$/, '$1 படிக்காதவை'],
    [/^No (.+) deliveries\.$/, '$1 விநியோகங்கள் இல்லை.'],
    [/^Order from (.+)$/, '$1 இலிருந்து ஆர்டர்'],
    [/^Loading (.+)…$/, '$1 ஏற்றப்படுகிறது…'],
  ]
  for (const [pattern, replacement] of patterns) {
    if (pattern.test(value)) return value.replace(pattern, replacement)
  }
  return value
}

const LanguageContext = createContext(null)

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => localStorage.getItem('tasteloop-language') || 'en')

  useEffect(() => {
    localStorage.setItem('tasteloop-language', language)
    document.documentElement.lang = language
  }, [language])

  const value = useMemo(() => ({
    language,
    setLanguage,
    toggleLanguage: () => setLanguage(current => current === 'en' ? 'ta' : 'en'),
    t: (key, fallback) => translations[language]?.[key] || fallback || key,
  }), [language])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useTranslation() {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useTranslation must be used inside LanguageProvider')
  return context
}
